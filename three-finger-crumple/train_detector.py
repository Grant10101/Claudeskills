"""Compile the recorded 3-finger pinches/expansions into detector thresholds (detector.json).

Each recording in gestures/ whose name contains "pinch" or "expand" is replayed;
its measured behaviour sets the thresholds, widened by safety margins so that
any 3-finger pinch/expansion passes while other gestures don't.

    python train_detector.py          # writes detector.json (+ static/detector-config.js)
"""
from __future__ import annotations

import json
import math
import statistics
from pathlib import Path

import gesture_lib as gl
from detector import features

ROOT = Path(__file__).resolve().parent


def measure(g: dict) -> dict:
    """Spread ratio etc. from the moment all fingers are down until the last lift (latest positions)."""
    ev = gl.events(g)
    downs = [e["t"] for e in ev if e["type"] == "down"]
    cur, base, last, all_down_t = {}, None, None, None
    for e in ev:
        cur[e["finger"]] = (e["x"], e["y"])
        if base is None and len(cur) == 3:
            base = [cur[k] for k in sorted(cur)]
            all_down_t = e["t"]
        if base is not None:
            last = features(base, [cur[k] for k in sorted(cur)])
    return {"name": g["name"], "id": g["id"], "fingers": len(g["strokes"]),
            "touchdown_spread_ms": max(downs) - min(downs),
            "ratio": last["ratio"], "radial": last["radial"], "rotation": last["rotation"],
            "start_spread_px": last["start_spread"]}


def main():
    recs = [gl.load_gesture(p) for p in sorted((ROOT / "gestures").glob("g-*.json"))]
    pinch = [measure(g) for g in recs if "pinch" in g["name"].lower()]
    expand = [measure(g) for g in recs if "expand" in g["name"].lower()]
    assert pinch and expand, "need at least one pinch and one expand recording"
    assert all(m["fingers"] == 3 for m in pinch + expand)

    t = {
        # every recording must have 3 fingers landing within this window (observed max x4, at least 300 ms)
        "max_touchdown_spread_ms": max(300, 4 * max(m["touchdown_spread_ms"] for m in pinch + expand)),
        # start following the fingers as soon as the group clearly starts closing / opening
        "engage_pinch_ratio": 0.92,
        "engage_expand_ratio": 1.08,
        "engage_radial": 0.3,
        # blue reaches area 0 when the spread hits the typical final pinch ratio (median of recordings)
        "pinch_target_ratio": round(statistics.median(m["ratio"] for m in pinch), 3),
        "expand_target_ratio": round(statistics.median(m["ratio"] for m in expand), 3),
        # recognized at release: fingers closed by ~30%+ / opened by 40%+ (weakest recording, with a wide margin)
        "commit_pinch_max_ratio": round(max(0.65, min(0.72, max(m["ratio"] for m in pinch) * 2)), 3),
        "commit_expand_min_ratio": round(max(1.4, min(m["ratio"] for m in expand) / 2), 3),
        "commit_radial": round(min(0.45, 0.5 * min(min(-m["radial"] for m in pinch), min(m["radial"] for m in expand))), 3),
        # fingers twisting more than this (avg, degrees) is a rotate, not a pinch (observed max x2.5, >= 45)
        "max_rotation_deg": round(max(45, 2.5 * max(abs(m["rotation"]) for m in pinch + expand))),
        "min_pinch_start_spread_px": 25,
    }
    out = {"compiled_from": pinch + expand, "thresholds": t}
    (ROOT / "detector.json").write_text(json.dumps(out, indent=1) + "\n")
    (ROOT / "static" / "detector-config.js").write_text(
        "// generated by train_detector.py from the recorded gestures — do not edit\n"
        "window.DETECTOR_CONFIG = " + json.dumps(t, indent=1) + ";\n")
    for m in pinch + expand:
        print(f"{m['name']:26} ratio {m['ratio']:.2f}  radial {m['radial']:+.2f}  rot {m['rotation']:+.0f}°  touchdown {m['touchdown_spread_ms']}ms")
    print(json.dumps(t, indent=1))


if __name__ == "__main__":
    main()
